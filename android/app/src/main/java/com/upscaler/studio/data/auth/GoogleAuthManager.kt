/**
 * Google Sign-In & Firebase Authentication bridge for Upscaler Studio.
 *
 * Responsibilities:
 *  - Manage Google Sign-In client and intents.
 *  - Authenticate with Firebase Authentication using Google credentials.
 *  - Provide persistent Firebase User ID (UID), profile info, and ID tokens.
 *  - Maintain user session state and sign-out coordination.
 */
class GoogleAuthManager private constructor(
    private val googleSignInClient: GoogleSignInClient,
    private val prefs: SharedPreferences,
) {

    private val _currentUserState = MutableStateFlow<FirebaseUser?>(null)
    val currentUserState: StateFlow<FirebaseUser?> = _currentUserState.asStateFlow()

    init {
        runCatching {
            _currentUserState.value = Firebase.auth.currentUser
        }
    }

    companion object {
        private const val TAG = "GoogleAuthManager"
        private const val PREFS_NAME = "upscaler_google_auth"
        private const val KEY_ID_TOKEN = "google_id_token"
        private const val KEY_GOOGLE_ID = "google_id"
        private const val KEY_FIREBASE_UID = "firebase_uid"
        private const val KEY_EMAIL = "google_email"
        private const val KEY_NAME = "google_name"
        private const val KEY_PICTURE = "google_picture"
        private const val KEY_FAILED_ATTEMPTS = "login_failed_attempts"
        private const val KEY_LOCKOUT_TIMESTAMP = "login_lockout_until"

        const val MAX_FAILED_ATTEMPTS = 5
        const val LOCKOUT_DURATION_SECONDS = 30L

        @Volatile private var instance: GoogleAuthManager? = null

        fun init(context: Context): GoogleAuthManager {
            return instance ?: synchronized(this) {
                instance ?: run {
                    val appContext = context.applicationContext

                    // Dynamically look up default_web_client_id generated by Google Services plugin, or fallback to string resource
                    val defaultWebClientIdRes = appContext.resources.getIdentifier("default_web_client_id", "string", appContext.packageName)
                    val generatedWebClientId = if (defaultWebClientIdRes != 0) {
                        runCatching { appContext.getString(defaultWebClientIdRes) }.getOrNull()
                    } else null

                    val configuredWebClientId = appContext.getString(R.string.google_web_client_id)
                    val effectiveWebClientId = (generatedWebClientId?.takeIf { it.isNotBlank() } ?: configuredWebClientId).trim()

                    val isValidWebClientId = effectiveWebClientId.isNotBlank() &&
                            !effectiveWebClientId.startsWith("REPLACE_ME", ignoreCase = true) &&
                            effectiveWebClientId.contains(".apps.googleusercontent.com")

                    val gsoBuilder = GoogleSignInOptions.Builder(GoogleSignInOptions.DEFAULT_SIGN_IN)
                        .requestEmail()
                        .requestProfile()

                    if (isValidWebClientId) {
                        Log.i(TAG, "Configuring Google Sign-In with Web Client ID: $effectiveWebClientId")
                        gsoBuilder.requestIdToken(effectiveWebClientId)
                    } else {
                        Log.w(TAG, "Google Web Client ID is a placeholder ('$effectiveWebClientId'). Basic Google Profile will be requested without Firebase ID token until configured.")
                    }

                    val gso = gsoBuilder.build()
                    val client = GoogleSignIn.getClient(appContext, gso)
                    val prefs = appContext.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
                    GoogleAuthManager(client, prefs).also { instance = it }
                }
            }
        }
    }

    /** Returns the Intent to launch Google account picking (start this via ActivityResultLauncher). */
    fun signInIntent(): Intent = googleSignInClient.signInIntent

    /**
     * Parses the result from [signInIntent] and persists the account.
     * Also triggers asynchronous Firebase Authentication with the Google ID token.
     * Returns [Result.success] with the [GoogleSignInAccount] or [Result.failure] with the error.
     */
    fun handleSignInResult(
        result: ActivityResult,
        onFirebaseComplete: (Result<FirebaseUser>) -> Unit = {}
    ): Result<GoogleSignInAccount> {
        return try {
            val data = result.data ?: return Result.failure(IllegalStateException("Sign-in returned no data."))
            val task = GoogleSignIn.getSignedInAccountFromIntent(data)
            val account = task.getResult(ApiException::class.java)
            saveAccount(account)
            signInWithFirebase(account, onFirebaseComplete)
            Result.success(account)
        } catch (e: ApiException) {
            Result.failure(e)
        } catch (e: Exception) {
            Result.failure(e)
        }
    }

    /**
     * Authenticates with Firebase Auth using the Google account credentials.
     */
    fun signInWithFirebase(
        account: GoogleSignInAccount,
        onComplete: (Result<FirebaseUser>) -> Unit = {}
    ) {
        val idToken = account.idToken
        if (idToken.isNullOrBlank()) {
            onComplete(Result.failure(IllegalStateException("No Google ID token provided. Please configure Web Client ID and SHA-1 in Firebase Console.")))
            return
        }
        try {
            val credential = GoogleAuthProvider.getCredential(idToken, null)
            Firebase.auth.signInWithCredential(credential)
                .addOnSuccessListener { authResult ->
                    val user = authResult.user
                    if (user != null) {
                        saveFirebaseUser(user)
                        _currentUserState.value = user
                        onComplete(Result.success(user))
                    } else {
                        onComplete(Result.failure(IllegalStateException("Firebase user is null.")))
                    }
                }
                .addOnFailureListener { error ->
                    Log.w(TAG, "Firebase Auth sign-in failed (continuing with Google Account): ${error.message}")
                    onComplete(Result.failure(error))
                }
        } catch (e: Exception) {
            Log.e(TAG, "Error initiating Firebase sign-in: ${e.message}", e)
            onComplete(Result.failure(e))
        }
    }

    suspend fun signInWithFirebaseAsync(account: GoogleSignInAccount): Result<FirebaseUser> =
        suspendCancellableCoroutine { continuation ->
            signInWithFirebase(account) { result ->
                if (continuation.isActive) {
                    continuation.resume(result)
                }
            }
        }

    // --- Failed Login & Lockout Protection (Brute Force Prevention) ---

    fun getFailedAttempts(): Int = prefs.getInt(KEY_FAILED_ATTEMPTS, 0)

    fun recordFailedAttempt(): Int {
        val count = getFailedAttempts() + 1
        prefs.edit().putInt(KEY_FAILED_ATTEMPTS, count).apply()
        if (count >= MAX_FAILED_ATTEMPTS) {
            val lockoutUntil = System.currentTimeMillis() + (LOCKOUT_DURATION_SECONDS * 1000L)
            prefs.edit().putLong(KEY_LOCKOUT_TIMESTAMP, lockoutUntil).apply()
        }
        return count
    }

    fun resetFailedAttempts() {
        prefs.edit()
            .remove(KEY_FAILED_ATTEMPTS)
            .remove(KEY_LOCKOUT_TIMESTAMP)
            .apply()
    }

    fun getLockoutRemainingSeconds(): Long {
        val lockoutUntil = prefs.getLong(KEY_LOCKOUT_TIMESTAMP, 0L)
        val now = System.currentTimeMillis()
        if (lockoutUntil > now) {
            return (lockoutUntil - now + 999L) / 1000L
        }
        return 0L
    }

    fun isLockedOut(): Boolean = getLockoutRemainingSeconds() > 0L

    /**
     * Authenticates with Firebase Auth using email and password.
     */
    fun signInWithEmail(
        email: String,
        pass: String,
        onComplete: (Result<FirebaseUser>) -> Unit = {}
    ) {
        val remaining = getLockoutRemainingSeconds()
        if (remaining > 0L) {
            onComplete(Result.failure(IllegalStateException("Too many failed attempts. Please wait ${remaining}s before trying again.")))
            return
        }
        if (email.isBlank() || pass.isBlank()) {
            onComplete(Result.failure(IllegalArgumentException("Email and password cannot be empty.")))
            return
        }
        try {
            Firebase.auth.signInWithEmailAndPassword(email.trim(), pass)
                .addOnSuccessListener { authResult ->
                    resetFailedAttempts()
                    val user = authResult.user
                    if (user != null) {
                        saveFirebaseUser(user)
                        _currentUserState.value = user
                        onComplete(Result.success(user))
                    } else {
                        onComplete(Result.failure(IllegalStateException("Firebase user is null.")))
                    }
                }
                .addOnFailureListener { error ->
                    Log.w(TAG, "Email sign-in failed: ${error.message}")
                    val msg = error.message.orEmpty()
                    val friendlyError = when {
                        error is com.google.firebase.auth.FirebaseAuthInvalidCredentialsException ||
                        msg.contains("invalid-credential", ignoreCase = true) ||
                        msg.contains("wrong-password", ignoreCase = true) ||
                        msg.contains("password is invalid", ignoreCase = true) ->
                            Exception("Incorrect password. Please try again.", error)

                        error is com.google.firebase.auth.FirebaseAuthInvalidUserException ||
                        msg.contains("user-not-found", ignoreCase = true) ->
                            Exception("No account found with this email. Please check or sign up.", error)

                        msg.contains("too-many-requests", ignoreCase = true) ->
                            Exception("Too many failed attempts. Please wait a moment before trying again.", error)

                        msg.contains("operation-not-allowed", ignoreCase = true) ||
                        msg.contains("sign-in provider is disabled", ignoreCase = true) ->
                            Exception("Email/Password sign-in is disabled in Firebase Console. Please enable it in Authentication > Sign-in method.", error)

                        else -> Exception(error.localizedMessage ?: "Login failed. Please try again.", error)
                    }
                    onComplete(Result.failure(friendlyError))
                }
        } catch (e: Exception) {
            Log.e(TAG, "Error initiating Email sign-in: ${e.message}", e)
            onComplete(Result.failure(e))
        }
    }

    /**
     * Creates a new Firebase Auth account with email and password.
     * Enforces: At least 8 characters, containing both letters and numbers.
     */
    fun signUpWithEmail(
        email: String,
        pass: String,
        onComplete: (Result<FirebaseUser>) -> Unit = {}
    ) {
        if (email.isBlank() || pass.isBlank()) {
            onComplete(Result.failure(IllegalArgumentException("Email and password cannot be empty.")))
            return
        }
        if (!android.util.Patterns.EMAIL_ADDRESS.matcher(email.trim()).matches()) {
            onComplete(Result.failure(IllegalArgumentException("Please enter a valid email address.")))
            return
        }
        if (pass.length < 8) {
            onComplete(Result.failure(IllegalArgumentException("Password must be at least 8 characters long.")))
            return
        }
        val hasLetter = pass.any { it.isLetter() }
        val hasDigit = pass.any { it.isDigit() }
        if (!hasLetter || !hasDigit) {
            onComplete(Result.failure(IllegalArgumentException("Password must contain both letters and numbers (0-9).")))
            return
        }
        try {
            Firebase.auth.createUserWithEmailAndPassword(email.trim(), pass)
                .addOnSuccessListener { authResult ->
                    resetFailedAttempts()
                    val user = authResult.user
                    if (user != null) {
                        saveFirebaseUser(user)
                        _currentUserState.value = user
                        onComplete(Result.success(user))
                    } else {
                        onComplete(Result.failure(IllegalStateException("Firebase user is null.")))
                    }
                }
                .addOnFailureListener { error ->
                    Log.w(TAG, "Email sign-up failed: ${error.message}")
                    val msg = error.message.orEmpty()
                    val friendly = when {
                        msg.contains("email-already-in-use", ignoreCase = true) ->
                            Exception("An account already exists with this email. Please log in instead.", error)
                        msg.contains("operation-not-allowed", ignoreCase = true) ||
                        msg.contains("sign-in provider is disabled", ignoreCase = true) ->
                            Exception("Email/Password sign-in is disabled in Firebase Console. Please enable it in Authentication > Sign-in method.", error)
                        msg.contains("weak-password", ignoreCase = true) ->
                            Exception("Password is too weak. Please use at least 8 characters with letters and numbers.", error)
                        else -> error
                    }
                    onComplete(Result.failure(friendly))
                }
        } catch (e: Exception) {
            Log.e(TAG, "Error initiating Email sign-up: ${e.message}", e)
            onComplete(Result.failure(e))
        }
    }

    /**
     * Sends password reset email for an account.
     */
    fun sendPasswordReset(
        email: String,
        onComplete: (Result<Unit>) -> Unit = {}
    ) {
        if (email.isBlank()) {
            onComplete(Result.failure(IllegalArgumentException("Please enter your email address.")))
            return
        }
        try {
            Firebase.auth.sendPasswordResetEmail(email.trim())
                .addOnSuccessListener {
                    onComplete(Result.success(Unit))
                }
                .addOnFailureListener { error ->
                    Log.w(TAG, "Password reset failed: ${error.message}")
                    onComplete(Result.failure(error))
                }
        } catch (e: Exception) {
            Log.e(TAG, "Error sending password reset: ${e.message}", e)
            onComplete(Result.failure(e))
        }
    }

    /** Current Firebase User instance (null if not authenticated with Firebase). */
    val firebaseUser: FirebaseUser?
        get() = runCatching { Firebase.auth.currentUser }.getOrNull()

    /** Primary User ID: Firebase UID, fallback to persisted UID or Google ID. */
    val firebaseUid: String?
        get() = firebaseUser?.uid ?: prefs.getString(KEY_FIREBASE_UID, null) ?: googleId

    /** Clean human-readable ID formatted as USR-XXXXXXXX (like USR-8F3D72E1). */
    val formattedDisplayId: String
        get() {
            val uid = firebaseUid
            return if (!uid.isNullOrBlank()) {
                val hexHash = Integer.toHexString(uid.hashCode()).uppercase().padStart(8, '0').take(8)
                "USR-$hexHash"
            } else {
                "USR-USER"
            }
        }

    /** User's display name or derived fallback from email. */
    val displayNameOrFallback: String
        get() = name?.takeIf { it.isNotBlank() }
            ?: email?.substringBefore("@")?.replaceFirstChar { if (it.isLowerCase()) it.titlecase() else it.toString() }
            ?: "Studio User"

    /** Initial letter for the circular profile avatar. */
    val initialLetter: String
        get() = (name?.firstOrNull { it.isLetter() } ?: email?.firstOrNull { it.isLetter() } ?: 'U').uppercase()

    /** Identity provider name (Google, Email, or Session). */
    val accountProvider: String
        get() {
            val user = firebaseUser
            if (user != null) {
                val providers = user.providerData.map { it.providerId }
                return when {
                    providers.contains("google.com") -> "Google"
                    providers.contains("password") -> "Email"
                    else -> "Firebase"
                }
            }
            return if (!idToken.isNullOrBlank()) "Google" else "Session"
        }

    /** True when authenticated with Firebase. */
    val isFirebaseSignedIn: Boolean
        get() = firebaseUser != null

    /** Currently persisted Google ID token (null if not signed in or token cleared). */
    val idToken: String?
        get() = prefs.getString(KEY_ID_TOKEN, null)

    val googleId: String? get() = prefs.getString(KEY_GOOGLE_ID, null)
    val email: String? get() = firebaseUser?.email ?: prefs.getString(KEY_EMAIL, null)
    val name: String? get() = firebaseUser?.displayName ?: prefs.getString(KEY_NAME, null)
    val pictureUrl: String? get() = firebaseUser?.photoUrl?.toString() ?: prefs.getString(KEY_PICTURE, null)

    /** True when a Google ID token, Firebase user, or email login is persisted. */
    val isSignedIn: Boolean get() = !idToken.isNullOrBlank() || isFirebaseSignedIn || !email.isNullOrBlank()

    private fun saveAccount(account: GoogleSignInAccount) {
        prefs.edit().apply {
            putString(KEY_ID_TOKEN, account.idToken)
            putString(KEY_GOOGLE_ID, account.id)
            putString(KEY_EMAIL, account.email)
            putString(KEY_NAME, account.displayName)
            account.photoUrl?.let { putString(KEY_PICTURE, it.toString()) }
        }.apply()
        syncToFirestore(
            uid = account.id ?: account.email ?: "google_user",
            email = account.email,
            name = account.displayName,
            provider = "Google"
        )
    }

    private fun saveFirebaseUser(user: FirebaseUser) {
        prefs.edit().apply {
            putString(KEY_FIREBASE_UID, user.uid)
            user.email?.let { putString(KEY_EMAIL, it) }
            user.displayName?.let { putString(KEY_NAME, it) }
            user.photoUrl?.let { putString(KEY_PICTURE, it.toString()) }
        }.apply()
        syncToFirestore(
            uid = user.uid,
            email = user.email,
            name = user.displayName,
            provider = if (user.providerData.any { it.providerId == "google.com" }) "Google" else "Email"
        )
    }

    private fun syncToFirestore(uid: String, email: String?, name: String?, provider: String) {
        Thread {
            try {
                val hexDocId = "user_" + Integer.toHexString(uid.hashCode()).lowercase().padStart(12, '0').take(12)
                val url = java.net.URL("https://firestore.googleapis.com/v1/projects/x-upscaler/databases/(default)/documents/users/$hexDocId")
                val conn = url.openConnection() as java.net.HttpURLConnection
                conn.requestMethod = "PATCH"
                conn.setRequestProperty("Content-Type", "application/json")
                conn.doOutput = true
                conn.connectTimeout = 5000
                conn.readTimeout = 5000

                val nowIso = java.text.SimpleDateFormat("yyyy-MM-dd'T'HH:mm:ss'Z'", java.util.Locale.US).apply {
                    timeZone = java.util.TimeZone.getTimeZone("UTC")
                }.format(java.util.Date())

                val json = org.json.JSONObject().apply {
                    put("fields", org.json.JSONObject().apply {
                        put("last_active", org.json.JSONObject().put("timestampValue", nowIso))
                        put("last_event", org.json.JSONObject().put("stringValue", "app_login"))
                        put("user_id", org.json.JSONObject().put("stringValue", uid))
                        put("display_name", org.json.JSONObject().put("stringValue", name ?: "Anonymous"))
                        put("account_provider", org.json.JSONObject().put("stringValue", provider))
                        if (!email.isNullOrBlank()) {
                            put("email", org.json.JSONObject().put("stringValue", email))
                        }
                    })
                }

                conn.outputStream.use { os ->
                    os.write(json.toString().toByteArray(Charsets.UTF_8))
                }
                val code = conn.responseCode
                Log.d(TAG, "Synced user profile to Firestore $hexDocId, response code: $code")
                conn.disconnect()
            } catch (e: Exception) {
                Log.w(TAG, "Firestore sync skipped: ${e.message}")
            }
        }.start()
    }

    /** Clears persisted Google credentials and signs the user out from both Firebase and Google. */
    fun signOut() {
        runCatching { Firebase.auth.signOut() }
        runCatching { googleSignInClient.signOut() }
        _currentUserState.value = null
        prefs.edit().clear().apply()
    }
}

/** Convenience extension to build the launcher inside a Compose activity/screen. */
fun ComponentActivity.googleSignInLauncher(
    onResult: (ActivityResult) -> Unit
): ActivityResultLauncher<Intent> =
    registerForActivityResult(ActivityResultContracts.StartActivityForResult()) {
        onResult(it)
    }

/** Extension so an [Activity] can obtain/initialise the singleton [GoogleAuthManager]. */
fun Activity.initGoogleAuth(): GoogleAuthManager = GoogleAuthManager.init(this)
